from __future__ import annotations

import uuid
from datetime import datetime, timezone
from enum import Enum
from typing import Optional

from pydantic import BaseModel, Field


# ── Research pipeline status ──────────────────────────────────

class ResearchStatus(str, Enum):
    PENDING = "pending"
    THINKING = "thinking"
    DECOMPOSING = "decomposing"
    SEARCHING = "searching"
    EVALUATING = "evaluating"
    DEEPENING = "deepening"
    SYNTHESIZING = "synthesizing"
    COMPLETE = "complete"
    FAILED = "failed"


# ── Core domain models ────────────────────────────────────────

class SubQuestion(BaseModel):
    id: str = Field(default_factory=lambda: uuid.uuid4().hex[:8])
    question: str
    search_queries: list[str] = Field(default_factory=list)
    perspective: str = ""


class QueryDecomposition(BaseModel):
    main_intent: str
    sub_questions: list[SubQuestion] = Field(default_factory=list)
    background_context: str = ""


class SearchResult(BaseModel):
    title: str = ""
    url: str = ""
    content: str = ""
    raw_content: Optional[str] = None
    compressed_content: Optional[str] = None  # summarize_sources output; reused by evaluate/report
    score: float = 0.0
    sub_question_id: str = ""


class EvaluatedSource(BaseModel):
    search_result: SearchResult
    relevance_score: float = 0.0
    key_findings: list[str] = Field(default_factory=list)
    keep: bool = False
    # Multi-criteria scores (Phase 3)
    information_density: float = 0.0
    source_authority: float = 0.0
    corroboration: float = 0.0


class Citation(BaseModel):
    number: int
    title: str
    url: str


class FactualClaim(BaseModel):
    claim: str
    source_indices: list[int] = Field(default_factory=list)
    confidence: float = 0.0


class ProgressEvent(BaseModel):
    research_id: str
    status: ResearchStatus = ResearchStatus.THINKING
    message: str = ""
    detail: str = ""
    progress_pct: float = 0.0
    timestamp: str = Field(default_factory=lambda: datetime.now(timezone.utc).isoformat())
    # Live streaming / telemetry fields
    thinking_chunk: str = ""         # incremental LLM token text
    component: str = ""              # human-readable step name (e.g. "Agent reasoning")
    hardware: str = ""               # "XPU" | "Xeon" | ""
    tps: float = 0.0                 # approximate output tokens/s
    model_name: str = ""             # model identifier, e.g. "meta-llama/Llama-3.1-8B-Instruct"
    hw_summary: dict = Field(default_factory=dict)  # per-hw stats emitted on complete
    input_source: str = ""           # "ui" | "cli" | "api" — set on COMPLETE event
    # Per-step token accounting (emitted when a tool step completes)
    step_start: bool = False         # True when a tool step is about to start
    step_done: bool = False          # True when a tool step has just finished
    step_input_tokens: int = 0       # LLM input tokens consumed by this step
    step_output_tokens: int = 0      # LLM output tokens generated by this step
    step_hardware: str = ""          # hardware used for this step's LLM call (e.g. "XPU")
    step_model: str = ""             # model used for this step's LLM call
    # Supervisor banner signals — a persistent top-of-list row that pulses while
    # the supervisor agent is thinking and accumulates its token count. Kept out
    # of the step_start/step_done flow so it doesn't grow the sub-agent list.
    supervisor_call_start: bool = False  # supervisor LLM call is starting
    supervisor_call_done: bool = False   # supervisor LLM call finished (tokens known)


class ResearchSession(BaseModel):
    id: str = Field(default_factory=lambda: uuid.uuid4().hex)
    query: str = ""
    status: ResearchStatus = ResearchStatus.PENDING
    input_source: str = "api"  # "ui" | "api" | "cli"
    # Opaque browser-local UUID — used to scope session history per user (empty = anonymous)
    client_id: str = ""
    decomposition: Optional[QueryDecomposition] = None
    search_results: list[SearchResult] = Field(default_factory=list)
    evaluated_sources: list[EvaluatedSource] = Field(default_factory=list)
    citations: list[Citation] = Field(default_factory=list)
    claims: list[FactualClaim] = Field(default_factory=list)
    report_markdown: str = ""
    error: Optional[str] = None
    created_at: str = Field(default_factory=lambda: datetime.now(timezone.utc).isoformat())


# ── LLM structured response models (used by instructor) ──────

class SubQuestionResponse(BaseModel):
    question: str
    search_queries: list[str]
    perspective: str


class DecompositionResponse(BaseModel):
    main_intent: str
    background_context: str = ""
    sub_questions: list[SubQuestionResponse]


class SourceEvaluation(BaseModel):
    source_index: int
    relevance_score: float = Field(ge=0.0, le=1.0)
    key_findings: list[str]
    keep: bool
    information_density: float = Field(ge=0.0, le=1.0, default=0.0)
    source_authority: float = Field(ge=0.0, le=1.0, default=0.0)


class EvaluationResponse(BaseModel):
    evaluations: list[SourceEvaluation]


class GapAnalysisResponse(BaseModel):
    follow_up_queries: list[str]


class SourceSummary(BaseModel):
    source_index: int
    key_claims: list[str]
    evidence: list[str]
    relevance_to_query: str


class MapSummaryResponse(BaseModel):
    summaries: list[SourceSummary]


class ClaimExtractionResponse(BaseModel):
    claims: list[FactualClaim]


class QueryClassification(BaseModel):
    category: int = Field(ge=1, le=3, description="1=simple factual, 2=quick lookup, 3=research")
    reasoning: str = Field(description="Brief explanation of why this category was chosen")
    search_queries: list[str] = Field(default_factory=list, description="Pre-generated search queries for Cat 2/3")
